// The writer of "The Generated Source". The output uses "\n" line ends, global:: type
// names, and no C# 14 feature, so it compiles in a consumer with C# 11 or later.
// Environment.NewLine is banned for an analyzer (RS1035), so each line ends with '\n'.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace BrutalUi.Generators;

/// <summary>
/// Writes the text of one generated element-table file. See the element-generator plan, "The Generated Source".
/// </summary>
internal static class ElementSourceWriter
{
    private const string Namespace = "BrutalUi.Markup";
    private const string LoaderType = "global::BrutalUi.Markup.TemplateLoader";
    private const string TypeInfoType = "global::BrutalUi.Markup.ElementTypeInfo";
    private const string RowType = "global::BrutalUi.Markup.AttributeRow";
    private const string RowKindType = "global::BrutalUi.Markup.AttributeRowKind";
    private const string CreateArgsType = "global::BrutalUi.Markup.ElementCreateArgs";
    private const string ElementType = "global::BrutalUi.Core.Element";
    private const string ContextType = "global::BrutalUi.Markup.AttributeContext";

    /// <summary>Builds the source text for the marked types of one assembly.</summary>
    /// <param name="assemblyId">The assembly id from <see cref="NameRules.ToIdentifier"/>.</param>
    /// <param name="models">The element models, sorted by XML name ordinal.</param>
    /// <returns>
    /// The source text, or an empty string when <paramref name="models"/> holds no model. The caller adds no
    /// source for an empty string.
    /// </returns>
    internal static string Write(string assemblyId, IReadOnlyList<ElementModel> models)
    {
        if (models.Count == 0)
        {
            return string.Empty;
        }

        var text = new StringBuilder(4096);
        AppendLine(text, 0, "// <auto-generated/>");
        AppendLine(text, 0, "#nullable enable");
        AppendLine(text, 0, "");
        AppendLine(text, 0, "namespace " + Namespace);
        AppendLine(text, 0, "{");
        AppendLine(text, 1, "internal static class " + assemblyId + "TemplateElements");
        AppendLine(text, 1, "{");

        AppendRegisterMethod(text, assemblyId, models);
        AppendSetters(text, models);

        AppendLine(text, 1, "}");
        AppendLine(text, 0, "}");
        return text.ToString();
    }

    /// <summary>Writes the register method with one <c>loader.Register</c> call per model.</summary>
    /// <param name="text">The builder to fill.</param>
    /// <param name="assemblyId">The assembly id.</param>
    /// <param name="models">The element models.</param>
    private static void AppendRegisterMethod(StringBuilder text, string assemblyId, IReadOnlyList<ElementModel> models)
    {
        AppendLine(text, 2, "internal static void Register" + assemblyId + "Elements(this " + LoaderType + " loader)");
        AppendLine(text, 2, "{");
        AppendLine(text, 3, "global::System.ArgumentNullException.ThrowIfNull(loader);");

        int setterIndex = 0;
        for (int i = 0; i < models.Count; i++)
        {
            ElementModel model = models[i];
            AppendLine(text, 3, "");
            AppendLine(text, 3, "loader.Register(new " + TypeInfoType);
            AppendLine(text, 3, "{");
            AppendLine(text, 4, "Name = " + Quote(model.XmlName) + ",");
            string create = model.FactoryCall ?? "new " + model.TargetType + "()";
            AppendLine(text, 4, "Create = static (" + CreateArgsType + " args) => " + create + ",");
            if (model.CreateRows.Length > 0 || model.SetRows.Length > 0)
            {
                AppendLine(text, 4, "Rows = new " + RowType + "[]");
                AppendLine(text, 4, "{");
                for (int c = 0; c < model.CreateRows.Length; c++)
                {
                    CreateRowModel createRow = model.CreateRows[c];
                    string kind = createRow.IsRequired ? "CreateRequired" : "Create";
                    AppendLine(
                        text,
                        5,
                        "new " + RowType + "(" + Quote(createRow.Name) + ", " + RowKindType + "." + kind + "),");
                }

                for (int r = 0; r < model.SetRows.Length; r++, setterIndex++)
                {
                    SetRowModel row = model.SetRows[r];
                    AppendLine(
                        text,
                        5,
                        "new " + RowType + "(" + Quote(row.RowName)
                        + ", static (" + ElementType + " element, " + ContextType + " context) => Set"
                        + setterIndex.ToString(CultureInfo.InvariantCulture)
                        + "(element, context)),");
                }

                AppendLine(text, 4, "},");
            }

            AppendLine(text, 4, "IsLeaf = " + (model.IsLeaf ? "true" : "false") + ",");
            AppendLine(text, 3, "});");
        }

        AppendLine(text, 2, "}");
    }

    /// <summary>Writes one private setter per set row, named <c>Set0</c>, <c>Set1</c>, and on, in output order.
    /// An enum row also writes its <c>Keywords&lt;n&gt;</c> field, with the same number as its setter.</summary>
    /// <param name="text">The builder to fill.</param>
    /// <param name="models">The element models.</param>
    private static void AppendSetters(StringBuilder text, IReadOnlyList<ElementModel> models)
    {
        int index = 0;
        foreach (ElementModel model in models)
        {
            for (int r = 0; r < model.SetRows.Length; r++, index++)
            {
                SetRowModel row = model.SetRows[r];
                if (row.Kind == ReadKind.Keyword)
                {
                    AppendLine(text, 2, "");
                    AppendKeywordArray(text, row, index);
                }

                AppendLine(text, 2, "");
                AppendLine(
                    text,
                    2,
                    "private static void Set" + index.ToString(CultureInfo.InvariantCulture)
                    + "(" + ElementType + " element, " + ContextType + " context)");
                AppendLine(text, 2, "{");
                AppendSetterBody(text, model, row, index);
                AppendLine(text, 2, "}");
            }
        }
    }

    /// <summary>Writes the keyword array field of one enum row.</summary>
    /// <param name="text">The builder to fill.</param>
    /// <param name="row">The enum set row.</param>
    /// <param name="index">The setter number of the row.</param>
    private static void AppendKeywordArray(StringBuilder text, SetRowModel row, int index)
    {
        List<string> quoted = new(row.Keywords.Length);
        foreach (KeywordModel keyword in row.Keywords)
        {
            quoted.Add(Quote(keyword.Keyword));
        }

        AppendLine(
            text,
            2,
            "private static readonly string[] Keywords" + index.ToString(CultureInfo.InvariantCulture)
            + " = new string[] { " + string.Join(", ", quoted) + " };");
    }

    /// <summary>Writes the body of one setter for the read kind of the row.</summary>
    /// <param name="text">The builder to fill.</param>
    /// <param name="model">The owning element model.</param>
    /// <param name="row">The set row.</param>
    /// <param name="index">The setter number of the row.</param>
    private static void AppendSetterBody(StringBuilder text, ElementModel model, SetRowModel row, int index)
    {
        string cast = "((" + model.TargetType + ")element)." + row.PropertyName;
        if (row.Kind == ReadKind.Text)
        {
            AppendLine(text, 3, cast + " = context.Value;");
            return;
        }

        if (row.Kind == ReadKind.Keyword)
        {
            AppendLine(text, 3, "if (context.TryReadKeyword(Keywords" + index.ToString(CultureInfo.InvariantCulture) + ", out int keywordIndex))");
            AppendLine(text, 3, "{");
            AppendLine(text, 4, "switch (keywordIndex)");
            AppendLine(text, 4, "{");
            for (int k = 0; k < row.Keywords.Length; k++)
            {
                AppendLine(text, 5, "case " + k.ToString(CultureInfo.InvariantCulture) + ":");
                AppendLine(text, 6, cast + " = " + row.Keywords[k].MemberName + ";");
                AppendLine(text, 6, "break;");
            }

            AppendLine(text, 4, "}");
            AppendLine(text, 3, "}");
            return;
        }

        string read = row.Kind switch
        {
            ReadKind.Number => "context.TryReadNumber(out float value)",
            ReadKind.Integer => "context.TryReadInteger(out int value)",
            ReadKind.Bool => "context.TryReadBool(out bool value)",
            ReadKind.Numbers2 => "context.TryReadNumbers(out global::Brutal.Numerics.float2 value)",
            ReadKind.Numbers4 => "context.TryReadNumbers(out global::Brutal.Numerics.float4 value)",
            ReadKind.Color => "context.TryReadColor(out global::BrutalUi.Core.Rgba8 value)",
            ReadKind.Texture => "context.TryReadTexture(out global::BrutalUi.Core.TextureHandle value)",
            _ => throw new ArgumentException($"ReadKind {row.Kind} has no generated read in this phase.", nameof(row)),
        };

        AppendLine(text, 3, "if (" + read + ")");
        AppendLine(text, 3, "{");
        AppendLine(text, 4, cast + " = value;");
        AppendLine(text, 3, "}");
    }

    /// <summary>Appends one source line with its indent and the '\n' line end.</summary>
    /// <param name="text">The builder to fill.</param>
    /// <param name="indent">The indent level. Each level adds four spaces.</param>
    /// <param name="line">The line text, without the line end.</param>
    private static void AppendLine(StringBuilder text, int indent, string line)
    {
        if (line.Length > 0)
        {
            text.Append(' ', indent * 4);
            text.Append(line);
        }

        text.Append('\n');
    }

    /// <summary>Quotes a name for the generated source.</summary>
    /// <param name="name">The name to quote.</param>
    /// <returns>The quoted literal.</returns>
    private static string Quote(string name)
    {
        return SymbolDisplay.FormatLiteral(name, quote: true);
    }
}
