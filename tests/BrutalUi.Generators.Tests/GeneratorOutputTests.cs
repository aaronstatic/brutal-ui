// The phase 4 output tests: the golden text, the name rules, the register order, the row order, the empty
// output, and the incremental cache. The step reasons come from the tracked pipeline of the harness driver.
using System;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Xunit;

namespace BrutalUi.Generators.Tests;

/// <summary>
/// Covers the generated source, the assembly id, the order of the types and rows, and the cache steps.
/// </summary>
public sealed class GeneratorOutputTests
{
    /// <summary>The golden test: the full text equals the pinned expected source.</summary>
    [Fact]
    public void TheGaugeSampleGivesTheExpectedSource()
    {
        GeneratorRun run = GeneratorHarness.Run(GeneratorHarness.GaugeSource);
        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace BrutalUi.Markup
            {
                internal static class SampleTemplateElements
                {
                    internal static void RegisterSampleElements(this global::BrutalUi.Markup.TemplateLoader loader)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(loader);

                        loader.Register(new global::BrutalUi.Markup.ElementTypeInfo
                        {
                            Name = "Gauge",
                            Create = static (global::BrutalUi.Markup.ElementCreateArgs args) => new global::Sample.Gauge(),
                            Rows = new global::BrutalUi.Markup.AttributeRow[]
                            {
                                new global::BrutalUi.Markup.AttributeRow("level", static (global::BrutalUi.Core.Element element, global::BrutalUi.Markup.AttributeContext context) => Set0(element, context)),
                            },
                            IsLeaf = false,
                        });
                    }

                    private static void Set0(global::BrutalUi.Core.Element element, global::BrutalUi.Markup.AttributeContext context)
                    {
                        if (context.TryReadNumber(out float value))
                        {
                            ((global::Sample.Gauge)element).Level = value;
                        }
                    }
                }
            }

            """,
            Assert.Single(run.GeneratedTexts).Value);
    }

    /// <summary>The kebab rule splits words and acronyms, the examples of the plan.</summary>
    [Fact]
    public void TheKebabRuleSplitsWordsAndAcronyms()
    {
        var cases = new (string Name, string Kebab)[]
        {
            ("Level", "level"),
            ("ScrollOffset", "scroll-offset"),
            ("Uv", "uv"),
            ("ScaleMode", "scale-mode"),
            ("HPBar", "hp-bar"),
            ("MaxHP", "max-hp"),
            ("Level2", "level2"),
            ("StretchToFill", "stretch-to-fill"),
        };
        foreach ((string name, string kebab) in cases)
        {
            Assert.Equal(kebab, NameRules.ToKebabCase(name));
        }
    }

    /// <summary>The register class name and method name come from the assembly name.
    /// <c>My-Game.UI</c> gives <c>MyGameUI</c>, and <c>3d.Ui</c> gives <c>_3dUi</c>.</summary>
    [Fact]
    public void TheRegisterNameComesFromTheAssemblyName()
    {
        GeneratorRun run = GeneratorHarness.Run(GeneratorHarness.GaugeSource, "My-Game.UI");
        Assert.True(run.GeneratedTexts.ContainsKey("MyGameUITemplateElements.g.cs"));
        string text = Assert.Single(run.GeneratedTexts).Value;
        Assert.Contains("internal static class MyGameUITemplateElements", text);
        Assert.Contains("RegisterMyGameUIElements", text);

        run = GeneratorHarness.Run(GeneratorHarness.GaugeSource, "3d.Ui");
        text = Assert.Single(run.GeneratedTexts).Value;
        Assert.Contains("internal static class _3dUiTemplateElements", text);
        Assert.Contains("Register_3dUiElements", text);
    }

    /// <summary>The types register in the order of their XML names, compared ordinal.</summary>
    [Fact]
    public void TheTypesRegisterInTheOrderOfTheirXmlNames()
    {
        GeneratorRun run = GeneratorHarness.Run("""
            using BrutalUi.Core;
            using BrutalUi.Markup;

            namespace Sample;

            [TemplateElement("Zeta")]
            internal sealed class Zulu : Element
            {
            }

            [TemplateElement("Alpha")]
            internal sealed class AlphaType : Element
            {
            }

            [TemplateElement("Mid")]
            internal sealed class Mike : Element
            {
            }
            """);
        string text = Assert.Single(run.GeneratedTexts).Value;
        int alpha = text.IndexOf("Name = \"Alpha\",", StringComparison.Ordinal);
        int mid = text.IndexOf("Name = \"Mid\",", StringComparison.Ordinal);
        int zeta = text.IndexOf("Name = \"Zeta\",", StringComparison.Ordinal);
        Assert.True(alpha >= 0, "Alpha missing");
        Assert.True(mid > alpha, $"Mid ({mid}) must follow Alpha ({alpha}).");
        Assert.True(zeta > mid, $"Zeta ({zeta}) must follow Mid ({mid}).");
    }

    /// <summary>A factory type writes its create rows before its set rows.</summary>
    [Fact]
    public void TheCreateRowsComeBeforeTheSetRows()
    {
        GeneratorRun run = GeneratorHarness.Run("""
            using BrutalUi.Core;
            using BrutalUi.Markup;

            namespace Sample;

            [TemplateElement("Meter")]
            internal sealed class Meter : Element
            {
                public Meter(int segments)
                {
                }

                [TemplateFactory]
                [TemplateCreateRow("segments")]
                internal static Element? Create(ElementCreateArgs args)
                {
                    return new Meter(1);
                }

                public float Value { get; set; }
            }
            """);
        string text = Assert.Single(run.GeneratedTexts).Value;
        int createRow = text.IndexOf("\"segments\", global::BrutalUi.Markup.AttributeRowKind.Create),", StringComparison.Ordinal);
        int setRow = text.IndexOf("=> Set0(element, context)),", StringComparison.Ordinal);
        Assert.True(createRow >= 0, "create row missing");
        Assert.True(setRow > createRow, $"set row ({setRow}) must follow the create row ({createRow}).");
    }

    /// <summary>An assembly with no marked type gets no source.</summary>
    [Fact]
    public void AnAssemblyWithNoMarkedTypeGetsNoSource()
    {
        GeneratorRun run = GeneratorHarness.Run("""
            using BrutalUi.Core;

            namespace Sample;

            internal sealed class Quiet : Element
            {
            }
            """);
        Assert.Empty(run.GeneratedTexts);
        Assert.Empty(run.Diagnostics);
    }

    /// <summary>An unrelated edit keeps each tracked step cached: the model steps read Cached or Unchanged,
    /// and the source output reads Cached.</summary>
    [Fact]
    public void AnUnrelatedEditKeepsEachStepCached()
    {
        GeneratorRun run = GeneratorHarness.Run(GeneratorHarness.GaugeSource);
        CSharpCompilation updated = GeneratorHarness.WithTree(
            run.Compilation,
            """
            namespace Unrelated;

            internal static class Note
            {
            }
            """,
            path: "Unrelated.cs");
        GeneratorRunResult rerun = GeneratorHarness.Rerun(run, updated);

        foreach (string trackingName in new[] { "TemplateElementModels", "TemplateElementSet" })
        {
            var reasons = GeneratorHarness.StepReasons(rerun, trackingName);
            Assert.NotEmpty(reasons);
            foreach (IncrementalStepRunReason reason in reasons)
            {
                Assert.True(
                    reason is IncrementalStepRunReason.Cached or IncrementalStepRunReason.Unchanged,
                    $"{trackingName}: unexpected reason {reason}.");
            }
        }

        var sourceReasons = GeneratorHarness.SourceOutputReasons(rerun);
        Assert.NotEmpty(sourceReasons);
        Assert.All(sourceReasons, static reason => Assert.Equal(IncrementalStepRunReason.Cached, reason));
    }

    /// <summary>An edit of a marked type runs the transform again: the model step reads Modified, and the new
    /// row name is in the text.</summary>
    [Fact]
    public void AnEditOfAMarkedTypeRunsTheTransformAgain()
    {
        GeneratorRun run = GeneratorHarness.Run(GeneratorHarness.GaugeSource);
        SyntaxTree original = run.Compilation.SyntaxTrees.Single();
        SyntaxTree edited = original.WithChangedText(SourceText.From(GeneratorHarness.GaugeSource.Replace("Level", "Power")));
        CSharpCompilation updated = run.Compilation.ReplaceSyntaxTree(original, edited);
        GeneratorRunResult rerun = GeneratorHarness.Rerun(run, updated);

        Assert.Equal(IncrementalStepRunReason.Modified, Assert.Single(GeneratorHarness.StepReasons(rerun, "TemplateElementModels")));
        string text = Assert.Single(rerun.GeneratedSources).SourceText.ToString();
        Assert.Contains("\"power\"", text);
        Assert.Contains("Power = value;", text);
    }
}
